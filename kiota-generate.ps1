# Kiota generation script for Exact Online API client in C#

$buildersGeneratedPath = "src/ExactOnline.Api.Client/Generated/Api/V1"
$modelsPath = "./src/ExactOnline.Api.Client/Generated/Models"
$extensionsModelsPath = "./src/ExactOnline.Api.Client/Extensions/Models"

Write-Output "⚙️ Generating C# client code..."
kiota generate `
    --cc `
    --ad false `
    --openapi "./resources/exactonline-openapi.json" `
    --clean-output `
    --language CSharp `
    --output "./src/ExactOnline.Api.Client/Generated" `
    --namespace-name "ExactOnline.Api.Client" `
    --class-name "ExactOnlineServiceClient" `

Write-Output "🔧 Patching models..."
$modelFiles = Get-ChildItem -Path $modelsPath -Filter "*.cs" | Where-Object {
    $_.Name -notlike "*Post.cs" -and $_.Name -notlike "*Put.cs" -and $_.Name -notlike "*_Response.cs" -and $_.Name -notlike "*Post_Response.cs" -and $_.Name -notlike "*Put_Response.cs" -and $_.Name -notlike "*_Results.cs" -and $_.Name -notlike "ExactOnlineMetadata*.cs" -and $_.Name -notlike "ODataError*.cs"
}

foreach ($file in $modelFiles) {
    $content = Get-Content -Path $file.FullName -Raw
    $oldString = 'Timestamp = n.GetLongValue();'
    $newString = 'Timestamp = n.GetTimestampAsLongValue();'
    
    if ($content -match [regex]::Escape($oldString)) {
        $newContent = $content.Replace($oldString, $newString)
        Set-Content -Path $file.FullName -Value $newContent -Encoding UTF8
    }
}

foreach ($file in $modelFiles) {
    $content = Get-Content -Path $file.FullName -Raw
    $oldString = 'TimeStampAsBigInt = n.GetLongValue();'
    $newString = 'TimeStampAsBigInt = n.GetTimestampAsLongValue();'
    
    if ($content -match [regex]::Escape($oldString)) {
        $newContent = $content.Replace($oldString, $newString)
        Set-Content -Path $file.FullName -Value $newContent -Encoding UTF8
    }
}

Write-Output "🔧 Patching response models..."
$responseModelFiles = Get-ChildItem -Path $modelsPath -Filter "*_Response.cs"

foreach ($file in $responseModelFiles) {
    $content = Get-Content -Path $file.FullName -Raw
    $oldString = 'var mappingValue = parseNode.GetChildNode("results")?.GetStringValue();'
    $newString = 'var mappingValue = parseNode.GetChildNode("results") != null ? "_Results" : null;'
    
    if ($content -match [regex]::Escape($oldString)) {
        $newContent = $content.Replace($oldString, $newString)
        Set-Content -Path $file.FullName -Value $newContent -Encoding UTF8
    }
}

Write-Output "🔧 Patching WithId and WithUserId request builders ..."
$withIdRequestBuilderFiles = Get-ChildItem -Path $buildersGeneratedPath -Recurse -Filter "*With*RequestBuilder.cs"
foreach ($file in $withIdRequestBuilderFiles) {
    $content = Get-Content -Path $file.FullName -Raw
    $oldString = '({id})'
    $newString = '(guid''{id}'')'
    
    if ($content -match [regex]::Escape($oldString)) {
        $content = $content.Replace($oldString, $newString)
    }

    $oldString = '({userid})'
    $newString = '(guid''{userid}'')'
    
    if ($content -match [regex]::Escape($oldString)) {
        $content = $content.Replace($oldString, $newString)
    }

    Set-Content -Path $file.FullName -Value $content -Encoding UTF8
}

$requestBuildersPath = "./src/ExactOnline.Api.Client/Extensions/RequestBuilders"
Write-Output "🧹 Cleaning RequestBuilders folder..."
Remove-Item -Path "$requestBuildersPath\*" -Recurse -Force

Write-Output "🔄 Generating partial RequestBuilder classes..."
$requestBuilderFiles = Get-ChildItem -Path $buildersGeneratedPath -Recurse -Filter "*RequestBuilder.cs" | Where-Object { $_.Name -notlike '*With*RequestBuilder.cs' }
foreach ($file in $requestBuilderFiles) {
    $className = [System.IO.Path]::GetFileNameWithoutExtension($file.Name)

    $resolvedPath = Resolve-Path $buildersGeneratedPath
    
    $subFolder = Split-Path ($file.FullName.Replace($resolvedPath, "")) -Parent

    $partialFilePath = Join-Path $requestBuildersPath (Join-Path $subFolder $file.Name)

    $partialFileFolder = Split-Path $partialFilePath -Parent
    New-Item -ItemType Directory -Path $partialFileFolder -Force | Out-Null

    $sourceContent = Get-Content -Path $file.FullName -Raw

    $line = $sourceContent | Where-Object { $_ -match '_Response\?> GetAsync\(Action<RequestConfiguration<' }
    if ($line -match 'Task<global::ExactOnline\.Api\.Client\.Models\.([A-Za-z0-9_]+)_Response\?>') {
        $itemClassName = $Matches[1]
    }
    else {
        # Skip file when no GetAsync method is found
        continue
    }

    if ($sourceContent -match 'namespace\s+([^;{]+)') {
        $namespace = $Matches[1].Trim()
    }
    else {
        continue
    }
            
    $contentLines = @(
        "// <auto-generated/>",
        "#nullable enable",
        "using System.Linq.Expressions;",
        "using ExactOnline.Api.Client.Models;",
        "using Microsoft.Kiota.Abstractions;",
        "using Microsoft.Kiota.Abstractions.Serialization;",
        "",
        "namespace $namespace;",
        "",
        "public partial class $className",
        "{",
        "    public async Task<${itemClassName}_Response?> GetAllAsync(Action<RequestConfiguration<${className}.${className}GetQueryParameters>>? requestConfiguration = default, CancellationToken cancellationToken = default)",
        "    {",
        "        var response = await GetAsync(requestConfiguration, cancellationToken);",
        "        if (response?.D?.${itemClassName}Results is null)",
        "        {",
        "            return response;",
        "        }",
        "",
        "        var allItems = new List<${itemClassName}>();",
        "        var currentResponse = response;",
        "", 
        "        while (true)",
        "        {",
        "            if (currentResponse?.D?.${itemClassName}Results?.Results is { } results)",
        "            {",
        "                allItems.AddRange(results);",
        "            }",
        "",
        "            var nextUrl = currentResponse?.D?.${itemClassName}Results?.Next;",
        "            if (string.IsNullOrEmpty(nextUrl))",
        "            {",
        "                break;",
        "            }",
        "",
        "            var nextRequestBuilder = new ${className}(nextUrl, RequestAdapter);",
        "            currentResponse = await nextRequestBuilder.GetAsync(cancellationToken: cancellationToken);",
        "        }",
        "",
        "        var finalResponse = new ${itemClassName}_Response",
        "        {",
        "            D = new ${itemClassName}_Response.${itemClassName}_Response_d",
        "            {",
        "                ${itemClassName} = allItems",
        "            }",
        "        };",
        "",
        "        return finalResponse;",
        "    }",
        "}"
    )
    
    $partialClassContent = $contentLines -join "`r`n"
    Set-Content -Path $partialFilePath -Value $partialClassContent -Encoding UTF8
}

Write-Output "🧹 Cleaning extensions model folder..."
Remove-Item -Path "$extensionsModelsPath\*" -Recurse -Force

Write-Output "🔄 Generating partial model classes..."
foreach ($file in $modelFiles) {
    $content = Get-Content -Path $file.FullName -Raw

    if ($content -notmatch 'public virtual IDictionary<string, Action<IParseNode>> GetFieldDeserializers\(\)') {
        continue
    }

    # Extract property mappings from GetFieldDeserializers method
    $pattern = '{\s*"([^"]+)",\s*n\s*=>\s*{\s*(\w+)\s*='
    $regexMatches = [regex]::Matches($content, $pattern)

    $mappings = @()
    foreach ($match in $regexMatches) {
        $jsonKey = $match.Groups[1].Value
        $propertyName = $match.Groups[2].Value
        $mappings += "        { nameof($propertyName), `"$jsonKey`" }"
    }

    $propertyMappingCode = @"
    internal static readonly Dictionary<string, string> PropertyMapping = new()
    {
$($mappings -join ",`r`n")
    };
"@

    $className = [System.IO.Path]::GetFileNameWithoutExtension($file.Name)
    $newContent = "// <auto-generated/>`r`nnamespace ExactOnline.Api.Client.Models;`r`n`r`npublic partial class ${className}`r`n{`r`n" + $propertyMappingCode + "`r`n}"

    $newFilePath = Join-Path $extensionsModelsPath $file.Name
    Set-Content -Path $newFilePath -Value $newContent -Encoding UTF8
}

Write-Output "🔄 Generating response extension classes..."

# Find all normal model files in the models directory
$modelFiles = Get-ChildItem -Path $modelsPath -Filter "*.cs" | Where-Object {
    $_.Name -notlike "*Post.cs" -and $_.Name -notlike "*Put.cs" -and $_.Name -notlike "*_Response.cs" -and $_.Name -notlike "*Post_Response.cs" -and $_.Name -notlike "*Put_Response.cs" -and $_.Name -notlike "*_Results.cs" -and $_.Name -notlike "ExactOnlineMetadata*.cs" -and $_.Name -notlike "ODataError*.cs"
}
foreach ($file in $modelFiles) {
    $className = [System.IO.Path]::GetFileNameWithoutExtension($file.Name)
    $responseFileName = "${className}_Response.cs"
    $responseFilePath = Join-Path $extensionsModelsPath "${className}_ResponseExtensions.cs"
    
    $sourceResponseModelPath = Join-Path $modelsPath $responseFileName
    $methodsContent = ""
    $responseClassName = "${className}_Response"

    if (Test-Path $sourceResponseModelPath) {
        $sourceResponseContent = Get-Content -Path $sourceResponseModelPath -Raw
        
        if ($sourceResponseContent -match "/// A collection of") {
            $methodsContent = $methodsContent + "    public static async Task<List<${className}>> AsItems(this Task<${responseClassName}?> task)`r`n"
            $methodsContent = $methodsContent + "    {`r`n"
            $methodsContent = $methodsContent + "        var d = (await task)?.D;`r`n"
            $methodsContent = $methodsContent + "        return d == null ? [] : d.${className} ?? d.${className}Results?.Results ?? [];`r`n"
            $methodsContent = $methodsContent + "    }`r`n"
        } else {
            $methodsContent = $methodsContent + "    public static async Task<${className}?> AsItem(this Task<${responseClassName}?> task)`r`n"
            $methodsContent = $methodsContent + "    {`r`n"
            $methodsContent = $methodsContent + "        var d = (await task)?.D;`r`n"
            $methodsContent = $methodsContent + "        return d == null ? null : (d.${className} ?? d.${className}Results?.Results ?? []).FirstOrDefault();`r`n"
            $methodsContent = $methodsContent + "    }`r`n"
        }
    }

    $contentLines = @(
        "// <auto-generated/>",
        "#nullable enable",
        "namespace ExactOnline.Api.Client.Models;",
        "",
        "public static class ${responseClassName}Extensions",
        "{",
        $methodsContent,
        "}"
    )
    
    $responseClassContent = ($contentLines -join "`r`n")
    
    Set-Content -Path $responseFilePath -Value $responseClassContent -Encoding UTF8
}

# Find all 'Post' and 'Get' response model files in the models directory
$modelFiles = Get-ChildItem -Path $modelsPath -Filter "*.cs" | Where-Object {
    $_.Name -clike "*Post_Response.cs" -or $_.Name -clike "*Get_Response.cs"
}
foreach ($file in $modelFiles) {
    $responseClassName = ([System.IO.Path]::GetFileNameWithoutExtension($file.Name))
    $className = $responseClassName.Replace("_Response", "") -creplace "Get$", ""
    $responseFilePath = Join-Path $extensionsModelsPath "${responseClassName}Extensions.cs"

    $contentLines = @(
        "// <auto-generated/>",
        "#nullable enable",
        "namespace ExactOnline.Api.Client.Models;",
        "",
        "public static class ${responseClassName}Extensions",
        "{",
        "    public static async Task<${className}?> AsItem(this Task<${responseClassName}?> task)"
        "    {"
        "        return (await task)?.D;"
        "    }"
        "}"
    )
    
    $responseClassContent = ($contentLines -join "`r`n")
    
    Set-Content -Path $responseFilePath -Value $responseClassContent -Encoding UTF8
}

Write-Output "✅ Classes generation completed"